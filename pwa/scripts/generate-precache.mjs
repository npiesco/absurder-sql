import { readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const pwaRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const staticRoot = resolve(pwaRoot, '.next', 'static');
const output = resolve(pwaRoot, 'public', 'sw-assets.js');

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const path = resolve(directory, entry.name);
      return entry.isDirectory() ? walk(path) : [path];
    }),
  );
  return files.flat();
}

const assets = (await walk(staticRoot))
  .map((file) => `/_next/static/${relative(staticRoot, file).split(sep).join('/')}`)
  .sort();

await writeFile(
  output,
  `// Generated by scripts/generate-precache.mjs after next build.\nself.__ABSURDER_PRECACHE = ${JSON.stringify(assets, null, 2)};\n`,
);

console.log(`Generated service-worker precache with ${assets.length} Next assets`);
